#!/usr/bin/env node
// Generates the hermetic OpenAPI inventory fixture
// (scripts/validate/fixtures/openapi-inventory.yaml) from a KingMinos OpenAPI
// JSON document — normally api-sync/openapi.snapshot.json or the live spec the
// API sync workflow just fetched.
//
// The fixture keeps only what the validator reads: discovery routes (so the
// parser is seen to skip them), every Bearer resource operation (operationId +
// security), and the `provider` path-parameter enum. Session/product-app ops
// and `/v1/admin/*` operator routes are dropped by the same rules
// `endpoint-map-openapi` applies. Output is deterministic (paths sorted, methods
// in a fixed order), so `api-sync-snapshot` can require fixture == render(snapshot).
//
//   node scripts/openapi-inventory.mjs <spec.json>           # write the fixture
//   node scripts/openapi-inventory.mjs <spec.json> --check   # exit 1 when stale
//   node scripts/openapi-inventory.mjs <spec.json> --out <path>

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  DISCOVERY,
  FIXTURE,
  bearerResourceOperations,
  resourceOperations,
} from './validate/rules/endpoint-map-openapi.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
export const MIN_PATHS = 10;

const HEADER = `# GENERATED by scripts/openapi-inventory.mjs from the KingMinos OpenAPI spec
# (api-sync/openapi.snapshot.json, fetched from https://api.kingminos.com/openapi.json).
# Do not edit by hand: the API sync workflow (.github/workflows/api-sync.yml)
# regenerates it, and the api-sync-snapshot rule fails when it drifts from the
# snapshot.
#
# Hermetic KingMinos OpenAPI Bearer resource inventory for offline validate/tests.
# Session/product-app ops (\`/v1/auth/*\`, \`/v1/account/*\`) declare no bearer
# security and \`/v1/admin/*\` operator routes are skipped, so neither is listed.
# Discovery routes are listed so the parser can be seen to skip them.
`;

/** Returns a problem string when the document is not a usable OpenAPI spec, else null. */
export function specProblem(spec) {
  if (!spec || typeof spec !== 'object' || Array.isArray(spec)) return 'not a JSON object';
  if (typeof spec.openapi !== 'string' || !spec.openapi) return 'missing `openapi` version';
  const paths = spec.paths && typeof spec.paths === 'object' ? Object.keys(spec.paths).length : 0;
  if (paths < MIN_PATHS) return `\`paths\` has ${paths} entries (expected at least ${MIN_PATHS})`;
  return null;
}

/** Parses and sanity-checks an OpenAPI JSON document; throws on anything unusable. */
export function parseSpec(text, source = 'spec') {
  let spec;
  try {
    spec = JSON.parse(text);
  } catch (err) {
    throw new Error(`${source} is not valid JSON: ${err.message}`);
  }
  const problem = specProblem(spec);
  if (problem) throw new Error(`${source} is not a usable OpenAPI document: ${problem}`);
  return spec;
}

function scalar(value) {
  const text = String(value);
  return /^[A-Za-z0-9_][A-Za-z0-9_.\-/ ]*$/.test(text) && !/ $/.test(text) && !/^(?:true|false|null|yes|no|on|off|~)$/i.test(text) && !/^[0-9.]+$/.test(text)
    ? text
    : JSON.stringify(text);
}

function deref(spec, value) {
  if (value && typeof value === 'object' && typeof value.$ref === 'string' && value.$ref.startsWith('#/')) {
    let node = spec;
    for (const part of value.$ref.slice(2).split('/')) node = node?.[part.replace(/~1/g, '/').replace(/~0/g, '~')];
    return node ?? value;
  }
  return value;
}

/** `provider` path-parameter enum for one path item (path level, then each method), or null. */
function providerEnum(spec, item) {
  const lists = [item.parameters, ...METHODS.map((m) => item[m]?.parameters)];
  const found = [];
  for (const params of lists) {
    if (!Array.isArray(params)) continue;
    for (const raw of params) {
      const param = deref(spec, raw);
      const schema = deref(spec, param?.schema);
      if (param?.name === 'provider' && param.in === 'path' && Array.isArray(schema?.enum)) {
        for (const id of schema.enum) if (typeof id === 'string' && !found.includes(id)) found.push(id);
      }
    }
  }
  return found.length ? found : null;
}

function securityLines(security, indent) {
  const pad = ' '.repeat(indent);
  const lines = [`${pad}security:`];
  for (const req of security) {
    const names = Object.keys(req ?? {});
    names.forEach((name, i) => {
      const scopes = Array.isArray(req[name]) ? req[name].map(scalar).join(', ') : '';
      lines.push(`${pad}${i === 0 ? '  - ' : '    '}${scalar(name)}: [${scopes}]`);
    });
  }
  return lines;
}

/** Renders the fixture YAML for an OpenAPI document. Pure and deterministic. */
export function renderInventoryFixture(spec) {
  const keep = new Map(); // route -> op
  for (const op of resourceOperations(spec)) keep.set(op.route, op);
  const bearer = new Set(bearerResourceOperations([...keep.values()]).map((op) => op.route));

  const lines = [HEADER.trimEnd(), `openapi: ${scalar(spec.openapi)}`, 'info:'];
  lines.push(`  title: ${scalar(spec.info?.title ?? 'KingMinos')}`);
  lines.push(`  version: ${scalar(spec.info?.version ?? '0')}`);
  lines.push('paths:');

  const schemes = new Set();
  const routes = Object.keys(spec.paths ?? {}).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  for (const routePath of routes) {
    const item = spec.paths[routePath];
    if (!item || typeof item !== 'object') continue;
    const discovery = DISCOVERY.test(routePath);
    const methods = METHODS.filter((m) => item[m] && typeof item[m] === 'object'
      && (discovery || bearer.has(`${m.toUpperCase()} ${routePath}`)));
    if (methods.length === 0) continue;

    lines.push(`  ${routePath}:`);
    const providers = discovery ? null : providerEnum(spec, item);
    if (providers) {
      lines.push(
        '    parameters:',
        '      - name: provider',
        '        in: path',
        '        required: true',
        '        schema:',
        '          type: string',
        `          enum: [${providers.map(scalar).join(', ')}]`,
      );
    }
    for (const method of methods) {
      const op = item[method];
      const body = [];
      if (typeof op.operationId === 'string' && op.operationId.trim()) body.push(`      operationId: ${scalar(op.operationId.trim())}`);
      if (!discovery) {
        const security = keep.get(`${method.toUpperCase()} ${routePath}`).security;
        for (const req of security) for (const name of Object.keys(req ?? {})) schemes.add(name);
        body.push(...securityLines(security, 6));
      }
      if (body.length === 0) lines.push(`    ${method}: {}`);
      else lines.push(`    ${method}:`, ...body);
    }
  }

  // Only schemes the spec defines, so Bearer detection (by scheme type, or by
  // the name `bearer` when the spec has no schemes) reads the same either way.
  const defined = [...schemes].sort()
    .map((name) => [name, deref(spec, spec.components?.securitySchemes?.[name])])
    .filter(([, scheme]) => scheme && typeof scheme === 'object');
  if (defined.length > 0) {
    lines.push('components:', '  securitySchemes:');
    for (const [name, scheme] of defined) {
      lines.push(`    ${scalar(name)}:`);
      if (typeof scheme.type === 'string') lines.push(`      type: ${scalar(scheme.type)}`);
      if (typeof scheme.scheme === 'string') lines.push(`      scheme: ${scalar(scheme.scheme)}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

function main(argv) {
  const args = [...argv];
  const check = args.includes('--check');
  const outIndex = args.indexOf('--out');
  const out = outIndex >= 0 ? path.resolve(args[outIndex + 1] ?? '') : path.join(ROOT, FIXTURE);
  const positional = args.filter((arg, i) => !arg.startsWith('--') && args[i - 1] !== '--out');
  if (positional.length !== 1 || (outIndex >= 0 && !args[outIndex + 1])) {
    console.error('usage: node scripts/openapi-inventory.mjs <openapi.json> [--check] [--out <path>]');
    return 2;
  }
  const source = positional[0];
  let rendered;
  try {
    rendered = renderInventoryFixture(parseSpec(readFileSync(source, 'utf8'), source));
  } catch (err) {
    console.error(`openapi-inventory: ${err.message}`);
    return 1;
  }
  const rel = out.startsWith(`${ROOT}${path.sep}`) ? path.relative(ROOT, out) : out;
  if (check) {
    let current = null;
    try {
      current = readFileSync(out, 'utf8');
    } catch {
      // Missing fixture counts as stale.
    }
    if (current === rendered) {
      console.log(`${rel} matches ${source}.`);
      return 0;
    }
    console.error(`${rel} is stale: regenerate it with \`node scripts/openapi-inventory.mjs ${source}\`.`);
    return 1;
  }
  writeFileSync(out, rendered);
  console.log(`Wrote ${rel} from ${source}.`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
